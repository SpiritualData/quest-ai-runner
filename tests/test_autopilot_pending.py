"""Pending work makes a quest due once a day even when its cadence is not, and the pass says how much.

The file contract is the one the SD meetings cron writes (``BACKLOG.md``): a Markdown table, or a
sentence when nothing is pending. Real file reads, a fake Quest client; no Drive and no network.
"""
from datetime import datetime, timezone

from quest_ai_runner.runner.autopilot import AutopilotPass
from quest_ai_runner.runner.autopilot_pending import (
    count_pending_rows, pass_due, pending_work_for)

from .test_autopilot import FakeAutopilotClient, _goal, _goals_payload, _now, _quest

TABLE = (
    "# Transcripts not yet summarized\n\nRegenerated by a cron.\n\n"
    "| Meeting date | Title | Drive file id | Transcript |\n| --- | --- | --- | --- |\n"
    "| 2026-10-15 | Office hour | `abc` | `transcripts/a.txt` |\n"
    "| 2026-10-15 | Accountability | `def` | `transcripts/b.txt` |\n")
NONE = "# Transcripts not yet summarized\n\nNone. Every transcript in the Drive folder has a summary.\n"


def test_count_rows_after_separator_only():
    assert count_pending_rows(TABLE) == 2
    assert count_pending_rows(NONE) == 0
    assert count_pending_rows("| only | a header |\n") == 0


def test_relative_file_resolves_under_quest_folder_and_unreadable_is_none(tmp_path):
    (tmp_path / "BACKLOG.md").write_text(TABLE)
    specs = {"q1": {"file": "BACKLOG.md", "label": "transcripts awaiting a summary"}}
    got = pending_work_for("q1", specs, {"q1": str(tmp_path)})
    assert (got.count, got.label) == (2, "transcripts awaiting a summary")
    assert pending_work_for("q2", specs, {"q1": str(tmp_path)}) is None      # not configured
    assert pending_work_for("q1", specs, {}) is None                         # relative, no folder
    assert pending_work_for("q1", {"q1": {"file": "gone.md"}}, {"q1": str(tmp_path)}) is None


def test_pass_due_only_daily_when_pending():
    cfg = {"cadence": "weekly", "last_pass_at": "2026-07-11T09:00:00Z"}   # yesterday
    assert pass_due(cfg, _now(), None, 0) is False
    assert pass_due(cfg, _now(), None, 3) is True
    ran_today = {"cadence": "weekly", "last_pass_at": "2026-07-12T01:00:00Z"}
    assert pass_due(ran_today, _now(), None, 3) is False                    # never twice a day


def _run(tmp_path, backlog):
    (tmp_path / "BACKLOG.md").write_text(backlog)
    q1 = _quest("q1", last_pass_at="2026-07-11T09:00:00Z")                  # weekly, not due
    goals = {"q1": _goals_payload(("day", "2026-07-12", [_goal("g1")]))}
    client = FakeAutopilotClient(quests=[q1], goals_by_quest=goals)
    passer = AutopilotPass(
        client, team_id="team1", now=_now, quest_folder_map={"q1": str(tmp_path)},
        pending_work={"q1": {"file": "BACKLOG.md", "label": "transcripts awaiting a summary"}})
    return passer.run({"text": "pass"})


def test_pending_runs_a_not_due_quest_and_reports_the_count(tmp_path):
    result = _run(tmp_path, TABLE)
    assert len(result.created_task_ids) == 1
    assert result.pending_work == [{"quest_id": "q1", "quest_label": "ship the thing",
                                    "count": 2, "label": "transcripts awaiting a summary"}]
    assert "ship the thing: 2 transcripts awaiting a summary." in result.summary_text()


def test_nothing_pending_leaves_the_cadence_gate_in_charge(tmp_path):
    result = _run(tmp_path, NONE)
    assert result.created_task_ids == []
    assert result.skipped[0]["reason"] == "cadence not due yet"
    assert result.pending_work == []


def test_schedule_creates_todays_pass_for_a_weekly_quest_with_pending_work(tmp_path):
    """The schedule and the gate read the same ``pass_due``: a weekly quest that ran yesterday is
    scheduled for today (not tomorrow) while its pending file has rows, from the real snapshot."""
    from quest_ai_runner.config import RunnerConfig
    from quest_ai_runner.runner.poller import Poller
    from .conftest import StubProvider, StubRetrieval
    from .test_autopilot_pass_task import FakePassClient

    (tmp_path / "BACKLOG.md").write_text(TABLE)
    client = FakePassClient(
        quests=[{"quest_id": "q1"}],
        autopilot_by_quest={"q1": {"mode": "act", "cadence": "weekly", "run_timezone": "UTC",
                                   "last_pass_at": "2026-07-11T09:00:00Z"}})
    cfg = RunnerConfig(
        quest_base_url="http://x", quest_api_key="qsk_test", team_id="team1",
        retrieval=StubRetrieval({}), model_provider=StubProvider(decisions=[]),
        quest_folder_map={"q1": str(tmp_path)},
        autopilot_pending_work={"q1": {"file": "BACKLOG.md"}})
    poller = Poller(cfg, state_path=None, client=client, now=_now)
    entry = poller._quest_schedule_snapshot()["q1"]
    assert entry["pending_work"] == 2
    assert poller._expected_quest_occurrence(entry)[0] == "2026-07-12"
    entry["pending_work"] = 0
    assert poller._expected_quest_occurrence(entry)[0] == "2026-07-13"
