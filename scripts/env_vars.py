"""Find every environment variable the library reads and render docs/configuration.md from them.

Used by ``check_structure.py`` (rule S15). A variable counts as read when its name appears as:
  * any string literal shaped ``QAR_*`` in ``quest_ai_runner/`` (this covers constants, tables and
    f-string prefixes that name a whole variable), or
  * the first argument of ``os.getenv`` / ``<env-like>.get/pop/setdefault``, or the subscript of an
    env-like mapping (``os.environ["X"]``, ``env["X"]``), when the name is ALL_CAPS with an underscore.
"Env-like" means the receiver's source text contains ``env``. The vendored code is skipped.
"""
from __future__ import annotations

import ast
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PKG = "quest_ai_runner"
_NAME = re.compile(r"^[A-Z][A-Z0-9]*(?:_[A-Z0-9]+)+$")
_QAR = re.compile(r"^QAR_[A-Z0-9_]*[A-Z0-9]$")
DOC = ROOT / "docs" / "configuration.md"
# Where a variable may be explained besides the generated table.
EXPLAINED_IN = ["README.md", ".env.example", "docs", "CLAUDE.md"]


def _envlike(node: ast.AST) -> bool:
    return "env" in ast.unparse(node).lower()


def env_vars_in_code(root: Path = ROOT) -> dict[str, list[str]]:
    """{variable: sorted repo-relative files that mention it}."""
    found: dict[str, set[str]] = {}
    for path in sorted((root / PKG).rglob("*.py")):
        if "vendor" in path.parts:
            continue
        rel = str(path.relative_to(root))
        try:
            tree = ast.parse(path.read_text())
        except SyntaxError:
            continue
        for n in ast.walk(tree):
            name = None
            if isinstance(n, ast.Constant) and isinstance(n.value, str) and _QAR.match(n.value):
                name = n.value
            elif (isinstance(n, ast.Call) and isinstance(n.func, ast.Attribute)
                  and n.func.attr in ("get", "getenv", "pop", "setdefault") and n.args
                  and isinstance(n.args[0], ast.Constant) and isinstance(n.args[0].value, str)
                  and _NAME.match(n.args[0].value) and (n.func.attr == "getenv" or _envlike(n.func.value))):
                name = n.args[0].value
            elif (isinstance(n, ast.Subscript) and isinstance(n.slice, ast.Constant)
                  and isinstance(n.slice.value, str) and _NAME.match(n.slice.value) and _envlike(n.value)):
                name = n.slice.value
            if name:
                found.setdefault(name, set()).add(rel)
    return {k: sorted(v) for k, v in sorted(found.items())}


def _doc_texts(root: Path) -> dict[str, str]:
    texts: dict[str, str] = {}
    for entry in EXPLAINED_IN:
        p = root / entry
        files = [p] if p.is_file() else sorted(p.rglob("*.md")) if p.is_dir() else []
        for f in files:
            rel = str(f.relative_to(root))
            if rel in ("docs/configuration.md",) or rel.startswith("docs/structure/"):
                continue
            texts[rel] = f.read_text(errors="ignore")
    return texts


def descriptions(root: Path = ROOT) -> dict[str, str]:
    """{variable: one-line description} from docs/structure/env_descriptions.csv."""
    import csv
    path = root / "docs" / "structure" / "env_descriptions.csv"
    if not path.exists():
        return {}
    with path.open(newline="") as fh:
        return {r["variable"]: r["description"] for r in csv.DictReader(fh)}


def render_env_doc(root: Path = ROOT) -> str:
    vars_ = env_vars_in_code(root)
    texts = _doc_texts(root)
    desc = descriptions(root)
    lines = [
        "# Environment variables",
        "",
        "Generated by `python scripts/check_structure.py --write-docs`; do not edit by hand. Structure rule",
        "S15 fails when a variable read anywhere in `quest_ai_runner/` is missing from this table, so the",
        "list cannot drift from the code. Configuration enters through `RunnerConfig` (see",
        "`docs/writing-a-consumer.md`): the config layer reads these variables, and `core/` reads none",
        "(its tunables arrive as `core.runtime_settings.CoreSettings`, see `RunnerConfig.core_settings`).",
        "A variable that is also a `RunnerConfig` field or a config-file key follows the rule in that",
        "document: the environment wins over the file.",
        "",
        f"{len(vars_)} variables. \"Read in\" lists the modules that name the variable; \"Explained in\" lists",
        "the docs and `.env.example` that describe what it does.",
        "",
        "| Variable | What it does | Read in | Explained in |",
        "|---|---|---|---|",
    ]
    for var, files in vars_.items():
        pat = re.compile(r"(?<![A-Z0-9_])" + re.escape(var) + r"(?![A-Z0-9_])")
        where = [rel for rel, t in texts.items() if pat.search(t)]
        short = ", ".join(f"`{f.removeprefix(PKG + '/')}`" for f in files[:3]) + (f" +{len(files) - 3}" if len(files) > 3 else "")
        expl = ", ".join(f"`{w}`" for w in where[:3]) + (f" +{len(where) - 3}" if len(where) > 3 else "") if where else "-"
        what = desc.get(var, "").replace("|", "/")
        lines.append(f"| `{var}` | {what} | {short} | {expl} |")
    return "\n".join(lines) + "\n"


def without_explained_in(text: str) -> str:
    """The doc minus its "Explained in" column, which follows other docs and so changes whenever they do."""
    out = []
    for ln in text.splitlines():
        out.append(ln.rsplit(" | ", 1)[0] + " |" if ln.startswith("| ") else ln)
    return "\n".join(out)
