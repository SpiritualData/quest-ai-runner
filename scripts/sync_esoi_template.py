#!/usr/bin/env python3
"""Regenerate the record template (docs/structure/esoi_template.csv) from the evolvable-structure skill.

Run from anywhere:  python scripts/sync_esoi_template.py [--skill PATH] [--check]
Exit 0 = written (or, with --check, already in sync), 1 = --check found drift, 2 = skill not found.

The skill's ``SKILL.md`` holds the "Intent template definitions": for each of Problem, Solution,
Implementation, Ideal and Metric, a definition, a ``Specify:`` list of fields, for a technology
solution an interface list, "What it's not" and "Connects to". The author refines that text, so it is
read here instead of being copied: this script is the only reader, and it writes

* ``docs/structure/esoi_template.csv``: ``entity, field_key, question, group, required``. Groups are
  ``specify`` (a required column of that entity's records), ``interface`` (optional, for a solution that is
  technology) and ``meta`` (the definition, "What it's not" and "Connects to" text, not a column).
* the generated section of ``docs/structure/STANDARD.md`` between the ``esoi-template`` markers.

Field keys are snake_case of the label (``Scoped Purpose`` -> ``scoped_purpose``). A bare question has no
label, so ``BARE_KEYS`` maps each to a short stable key by the words that identify it; refining the wording
of a question keeps its key as long as those words stay. An unmapped bare question gets a key from its
first words and is reported, so it can be given a stable key here.

The parser is tolerant: an empty ``- `` bullet (an unfinished section) is skipped and counted, bullets and
indentation may vary, and a missing section is reported, not fatal.
"""
from __future__ import annotations

import argparse
import csv
import io
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from sync_standing_instructions import skill_path  # noqa: E402  (reuses the skill-path handling and env override)

REPO = Path(__file__).resolve().parent.parent
TEMPLATE_CSV = REPO / "docs" / "structure" / "esoi_template.csv"
STANDARD = REPO / "docs" / "structure" / "STANDARD.md"
START = "<!-- esoi-template:start (generated by scripts/sync_esoi_template.py; do not edit) -->"
END = "<!-- esoi-template:end -->"
ENTITIES = ["problem", "solution", "implementation", "ideal", "metric"]
COLUMNS = ["entity", "field_key", "question", "group", "required"]

# (entity, regex on the lowercased question, key). First match wins. Keep these as keywords of the idea,
# not of the wording, so refining a question does not rename its column.
BARE_KEYS = [
    ("problem", r"what is the problem", "problem"),
    ("problem", r"\bwho\b", "who_has_it"),
    ("problem", r"\bmatter", "why_it_matters"),
    ("problem", r"\bhard\b|difficult", "why_hard"),
    ("problem", r"workaround|already attempt|existing", "existing_attempts"),
    ("solution", r"when and how|other information", "usage_notes"),
    ("solution", r"effects", "effects"),
]
META_KEYS = {"definition": "definition", "what_it_is_not": "what it's not", "connects_to": "connects to"}
HEADER = re.compile(r"^(specify|if technology[^:]*|what it'?s not|connects to)\s*:\s*(.*)$", re.I)
ITEM = re.compile(r"^-\s+\*\*(\w[\w ]*)\*\*\s*:\s*(.*)$")
LABELLED = re.compile(r"^([A-Z][A-Za-z]*(?: [A-Za-z]+){0,3}):\s*(.*)$")


def snake(text: str) -> str:
    text = re.sub(r"\([^)]*\)", " ", text)
    return re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")


def clean(text: str) -> str:
    return re.sub(r"\s+", " ", text.replace("**", "")).strip()


def template_lines(skill_text: str) -> list[str]:
    """The lines of the intent template block: from its heading line to the first unindented line that is
    neither an item nor blank (or the next ``## `` heading)."""
    lines = skill_text.splitlines()
    start = next((i for i, line in enumerate(lines) if line.lower().startswith("intent template definitions")), None)
    if start is None:
        return []
    block = []
    for line in lines[start + 1:]:
        if line.startswith("#"):
            break
        if line.strip() and not line.startswith((" ", "\t")) and not ITEM.match(line):
            break
        block.append(line)
    return block


def field_key(entity: str, text: str) -> tuple[str, str, bool]:
    """(key, question, mapped) for one field line with its bullet removed."""
    labelled = LABELLED.match(text)
    if labelled and "?" not in labelled.group(1):
        return snake(labelled.group(1)), clean(labelled.group(2)) or clean(labelled.group(1)), True
    lowered = text.lower()
    for ent, pattern, key in BARE_KEYS:
        if ent == entity and re.search(pattern, lowered):
            return key, clean(text), True
    if "?" not in text and len(snake(text).split("_")) <= 3:
        return snake(text), clean(text), True            # a bare label such as Parameters or Advantages
    words = [w for w in snake(text).split("_") if w not in {"what", "is", "the", "a", "an", "of", "does", "do", "how", "would"}]
    return "_".join(words[:3]) or "field", clean(text), False


def parse(skill_text: str) -> tuple[list[dict], list[str]]:
    """The template rows and a list of notes about what was parsed, skipped or guessed."""
    notes: list[str] = []
    rows: list[dict] = []
    block = template_lines(skill_text)
    if not block:
        return rows, ["no 'Intent template definitions' block found"]
    items: list[dict] = []
    current: dict | None = None
    section = ""
    for raw in block:
        if not raw.strip():
            continue
        line = raw.strip()
        item = ITEM.match(line) if not raw.startswith((" ", "\t")) else None
        if item:
            current = {"entity": item.group(1).strip().lower(), "definition": item.group(2).strip(),
                       "specify": [], "interface": [], "not": [], "connects": [], "empty": 0}
            items.append(current)
            section = "definition"
            continue
        if current is None:
            continue
        stripped = re.sub(r"^-\s*", "", line)
        header = HEADER.match(stripped)
        if header:
            name = header.group(1).lower()
            section = "specify" if name == "specify" else "interface" if name.startswith("if technology") else \
                "not" if name.startswith("what") else "connects"
            if header.group(2).strip() and section in ("not", "connects"):
                current[section].append(header.group(2).strip())
            continue
        if line in ("-", ""):
            current["empty"] += 1
            continue
        if section in ("specify", "interface"):
            current[section].append(stripped)
        elif section in ("not", "connects"):
            current[section].append(stripped)
        elif section == "definition":
            current["definition"] += " " + stripped
    seen = {i["entity"] for i in items}
    for missing in [e for e in ENTITIES if e not in seen]:
        notes.append(f"{missing}: section missing from the skill")
    for item in items:
        entity = item["entity"]
        rows.append({"entity": entity, "field_key": "definition", "question": clean(item["definition"]),
                     "group": "meta", "required": "no"})
        keys: set[str] = set()
        for group in ("specify", "interface"):
            for text in item[group]:
                key, question, mapped = field_key(entity, text)
                if key in keys:
                    notes.append(f"{entity}: duplicate key {key!r} skipped")
                    continue
                keys.add(key)
                if not mapped:
                    notes.append(f"{entity}: bare question {question!r} has no entry in BARE_KEYS; key {key!r} guessed")
                rows.append({"entity": entity, "field_key": key, "question": question, "group": group,
                             "required": "yes" if group == "specify" else "no"})
        for name, key in (("not", "what_it_is_not"), ("connects", "connects_to")):
            if item[name]:
                rows.append({"entity": entity, "field_key": key, "question": clean(" ".join(item[name])),
                             "group": "meta", "required": "no"})
        if item["empty"]:
            notes.append(f"{entity}: {item['empty']} empty bullet(s) skipped (section unfinished)")
        fields = [r for r in rows if r["entity"] == entity and r["group"] == "specify"]
        notes.append(f"{entity}: {len(fields)} required field(s), "
                     f"{sum(1 for r in rows if r['entity'] == entity and r['group'] == 'interface')} interface field(s)")
    return rows, notes


def render_csv(rows: list[dict]) -> str:
    buf = io.StringIO()
    writer = csv.DictWriter(buf, fieldnames=COLUMNS, lineterminator="\n")
    writer.writeheader()
    writer.writerows(rows)
    return buf.getvalue()


def render_section(rows: list[dict]) -> str:
    """The generated STANDARD.md section: one table per entity of the fields its records carry."""
    out = [START, "", "Generated from the skill's intent template by `python scripts/sync_esoi_template.py`; the",
           "records in this folder carry exactly these columns (a `Specify:` field is required, an interface field is",
           "optional and meant for a solution that is technology).", ""]
    for entity in ENTITIES:
        mine = [r for r in rows if r["entity"] == entity]
        if not mine:
            continue
        meta = {r["field_key"]: r["question"] for r in mine if r["group"] == "meta"}
        out.append(f"**{entity.capitalize()}**: {meta.get('definition', '')}")
        out.append("")
        out.append("| Column | Required | Question |")
        out.append("|---|---|---|")
        for r in mine:
            if r["group"] != "meta":
                out.append(f"| `{r['field_key']}` | {r['required']} | {r['question'].replace('|', '/')} |")
        for key, label in (("what_it_is_not", "What it is not"), ("connects_to", "Connects to")):
            if key in meta:
                out.append("")
                out.append(f"{label}: {meta[key]}")
        out.append("")
    out.append(END)
    return "\n".join(out)


def apply_section(standard_text: str, section: str) -> str:
    if START in standard_text and END in standard_text:
        head, rest = standard_text.split(START, 1)
        return head + section + rest.split(END, 1)[1]
    return standard_text.rstrip("\n") + "\n\n## Record fields (generated)\n\n" + section + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--skill", help="path to the skill's SKILL.md (default: the QAR_ESOI_SKILL env var, then the maintainers' corpus)")
    ap.add_argument("--check", action="store_true", help="exit 1 when esoi_template.csv or the STANDARD.md section is stale")
    args = ap.parse_args(argv)
    path = skill_path(args.skill)
    if not path.exists():
        print(f"skill not found: {path.name} (set QAR_ESOI_SKILL or pass --skill)", file=sys.stderr)
        return 2
    rows, notes = parse(path.read_text())
    for note in notes:
        print(f"note: {note}")
    if not rows:
        print("nothing parsed; refusing to write", file=sys.stderr)
        return 2
    csv_text, standard = render_csv(rows), apply_section(STANDARD.read_text(), render_section(rows))
    if args.check:
        stale = [name for name, want, have in (
            ("esoi_template.csv", csv_text, TEMPLATE_CSV.read_text() if TEMPLATE_CSV.exists() else ""),
            ("STANDARD.md section", standard, STANDARD.read_text())) if want != have]
        print("stale: " + ", ".join(stale) + " (run scripts/sync_esoi_template.py)" if stale else "esoi template ok")
        return 1 if stale else 0
    TEMPLATE_CSV.write_text(csv_text)
    STANDARD.write_text(standard)
    print(f"wrote {TEMPLATE_CSV.name} ({len(rows)} rows) and the STANDARD.md section")
    return 0


if __name__ == "__main__":
    sys.exit(main())
