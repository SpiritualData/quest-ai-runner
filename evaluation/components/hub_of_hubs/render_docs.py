"""Rewrites the generated block of ``docs/hub-of-hubs.md`` from the hub's registry and QAR's reading, in place (never appended).
Run: ``python3 evaluation/components/hub_of_hubs/render_docs.py`` (add ``--check`` to exit 1 when the file is out of date).
Day counts are left out on purpose, so the file changes only when a fact changes."""
import sys
from pathlib import Path

HERE = Path(__file__).resolve()
sys.path.insert(0, str(HERE.parents[1]))
sys.path.insert(0, str(HERE.parents[3]))

import hub_of_hubs  # noqa: E402,F401  (puts the hub package on the path)
from hubofhubs import evaluate_seats, render_docs  # noqa: E402

from hub_of_hubs.binding import REPO, binding  # noqa: E402

DOC = REPO / "docs" / "hub-of-hubs.md"
BEGIN = "<!-- hub-table:begin (generated by evaluation/components/hub_of_hubs/render_docs.py; do not edit) -->"
END = "<!-- hub-table:end -->"


def block():
    facts, seat_facts, connections, numbers = evaluate_seats(binding())
    covered = {a for f in facts.values() for a in [f["area"]] if f["covered"]}
    return "\n\n".join([
        f"The registry's {len(facts)} areas are research categories, mostly arms or tools inside the hub's seats; the seam, selectable, "
        "by-configuration and fake-hub checks are made once per seat, and only for the "
        f"{numbers['seats_to_connect']} seats with an adopt or coexist area. QAR's arms cover {len(covered)} areas today. An adopt or coexist area "
        "no arm covers is an arm gap: research to build or connect through the hub's defaults, not a missing binding (the hub's `docs/registry.md` lists every area).",
        render_docs.seat_reading(seat_facts),
        "The areas QAR's arms cover:\n\n" + render_docs.seat_table(facts=facts, areas=covered),
        "Reading of the hub's scorer on QAR:\n\n" + render_docs.metric_lines(numbers, facts)])


def main(argv):
    text = DOC.read_text(encoding="utf-8")
    new = render_docs.rewrite(text, BEGIN, END, block())
    if "--check" in argv:
        if new != text:
            print("docs/hub-of-hubs.md is out of date: run python3 evaluation/components/hub_of_hubs/render_docs.py")
            return 1
        return 0
    DOC.write_text(new, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
