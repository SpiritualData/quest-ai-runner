"""Writes the generated block of ``docs/hub-of-hubs.md`` from ``esoi/hubs.csv`` and the metric, in place (never appended), the
same idea as ``esoi check --write-docs``. Run: ``python3 evaluation/components/hub_of_hubs/render_docs.py`` (add ``--check`` to
exit 1 when the file is out of date). The text outside the markers is hand-written and never touched. Day counts are left out of the file on purpose, so it
changes only when a fact changes (a row, a capability, a code finding, or an area crossing the staleness bar)."""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve()
sys.path.insert(0, str(HERE.parents[1]))
sys.path.insert(0, str(HERE.parents[3]))

from hub_of_hubs import registry  # noqa: E402

DOC = registry.REPO / "docs" / "hub-of-hubs.md"
BEGIN, END = "<!-- hub-table:begin (generated by evaluation/components/hub_of_hubs/render_docs.py; do not edit) -->", "<!-- hub-table:end -->"


def names(cell):
    return ", ".join(n for n, _url, _lic in registry.parse_hubs(cell)) or "none yet"


def block():
    hubs = registry.read("hubs.csv")
    facts, caps = registry.all_facts()
    m = registry.metrics(facts, caps)
    by_area = {f["area"]: f for f in facts}
    lines = [BEGIN, "",
             "| Area | Built on today | Candidates | Connect | Researched | Freshness |", "|---|---|---|---|---|---|"]
    for h in hubs:
        f = by_area[h["area"]]
        lines.append(f"| {h['area']} | {names(h['current_hubs'])} | {'; '.join(registry.split(h['candidate_hubs']))} | "
                     f"{h['connect']} | {h['last_researched']} | {'fresh' if f['fresh'] else 'STALE'} |")
    stale = [f["area"] for f in facts if not f["fresh"]]
    lines += ["", "Metric `hub_of_hubs` (recomputed by `render_docs.py`, from the registry and a static scan of the code):", "",
              f"- coverage (areas with a hub or a recorded decision): {m['coverage']:.2f}",
              f"- integration by configuration (capabilities needing no code per integration): {m['config_share']:.2f}",
              f"- research freshness: share of areas researched within {registry.STALENESS_DAYS} days {m['fresh_share']:.2f}; "
              f"stale: {', '.join(stale) or 'none'} (days since each date: `esoi run hub_of_hubs --impl registry_scan`)",
              f"- code: areas with one seam {m['seam_share']:.2f}, selectable by metric {m['selectable_share']:.2f}, "
              f"vendor branches in core {m['vendor_branches']}",
              f"- score: {m['score']:.3f}", "", END]
    return "\n".join(lines)


def render(text):
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if not pattern.search(text):
        raise SystemExit("docs/hub-of-hubs.md has no generated block markers")
    return pattern.sub(lambda _m: block(), text)


def main(argv):
    text = DOC.read_text(encoding="utf-8")
    new = render(text)
    if "--check" in argv:
        if new != text:
            print("docs/hub-of-hubs.md is out of date: run python3 evaluation/components/hub_of_hubs/render_docs.py")
            return 1
        return 0
    DOC.write_text(new, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
