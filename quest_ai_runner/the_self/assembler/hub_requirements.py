"""What QAR's hub assembly needs from its environment, and whether it is there.

The hub's arms declare their needs (``REQUIRES``: variables, API keys, packages, programs, services) and ``esoi`` checks them.
QAR does not restate them: this module asks QAR's hub assembly (``hub.child()``) for the closure of what QAR would use, runs
esoi's check offline, and reports the unmet items with the remedy line esoi gives for each. Nothing here prints or returns a
variable's value, only names and statuses, and nothing calls a model or the network.

What QAR "uses" is the selected arm of every hub seat (the web search backend is an external seat QAR
provides itself, so it is left out) plus the four vendor arms of ``vendor-model-caller`` that ``hub.make_provider`` builds on
demand. The vendor arms only feed the ``.env.example`` template and the variable descriptions: no single vendor key is required
(a keyless ``claude_cli`` lane needs none), so they are never reported as unmet.

A seat whose selected arm cannot be built (a record names an arm no code declares) is reported as ``unresolved`` rather than
hiding every other finding.

Command line (the generated part of ``.env.example`` is owned by the hub's declarations)::

    python -m quest_ai_runner requirements --write-env-example .env.example
    python -m quest_ai_runner requirements --check-env-example .env.example
"""
from __future__ import annotations

import os
import sys
from dataclasses import dataclass, field
from typing import Any, Dict, List, Mapping, Optional, Sequence, Tuple

from esoi import requirements as esoi_requirements
from esoi import AssemblyError

from quest_ai_runner.the_self.assembler import hub

EXTERNAL_SEATS = {"web-search": object()}   # the seat QAR provides itself (its search member), so not in the closure; the model seat is QAR's own router arm, so it is
BEGIN_MARK = "# >>> hub-declared variables: generated by `python -m quest_ai_runner requirements --write-env-example`; do not edit"
END_MARK = "# <<< hub-declared variables"
DOCTOR_COMMAND = "quest-ai-runner doctor"


@dataclass(frozen=True)
class Item:
    """One requirement: what it is, whether it is met, and the one line that fixes it."""
    label: str
    kind: str
    status: str
    required: bool
    blocking: bool
    remedy: str
    used_by: Tuple[str, ...]

    def line(self) -> str:
        text = f"[{self.status}] {self.label}" + ("" if self.required else " (optional)")
        if self.used_by:
            text += f"  <- {', '.join(self.used_by[:3])}"
        return text


@dataclass
class Report:
    """The requirement checks of QAR's hub assembly. ``unresolved`` maps a seat to why its selected arm cannot be built."""
    items: List[Item] = field(default_factory=list)
    unresolved: Dict[str, str] = field(default_factory=dict)

    def unmet(self) -> List[Item]:
        """The unmet items that stop an arm being built (required env, api, python or binary): what the startup notice counts."""
        return [item for item in self.items if item.blocking]

    def failing(self) -> List[Item]:
        """Unmet and required (esoi's exit-code-1 rule), plus a download that will not fit."""
        return [item for item in self.items if item.status == esoi_requirements.UNMET and (item.required or item.kind == "download")]

    @property
    def exit_code(self) -> int:
        """esoi's convention: 0 everything met, 1 something unmet (or a seat that cannot be built)."""
        return 1 if self.failing() or self.unresolved else 0

    def lines(self) -> List[str]:
        """One line per item, the remedy under each unmet one; unresolved seats last. No variable values."""
        out: List[str] = []
        for item in self.items:
            out.append(item.line())
            if item.status == esoi_requirements.UNMET and item.remedy:
                out.append(f"    remedy: {item.remedy}")
        for seat, why in sorted(self.unresolved.items()):
            out.append(f"[unresolved] seat {seat}: {why}")
        return out

    def as_json(self) -> Dict[str, Any]:
        return {"schema": "quest_ai_runner.the_self.assembler.hub_requirements/1", "exit": self.exit_code,
                "unmet": [item.label for item in self.failing()], "unresolved": dict(self.unresolved),
                "items": [{"label": i.label, "kind": i.kind, "status": i.status, "required": i.required, "remedy": i.remedy,
                           "used_by": list(i.used_by)} for i in self.items]}


def members_for(seats: Sequence[str], assembler=None, every_arm: bool = False) -> Tuple[list, Dict[str, str]]:
    """The closure members of ``seats`` one seat at a time, so one unbuildable selection does not hide the others."""
    assembler = assembler or hub.child()
    members: list = []
    unresolved: Dict[str, str] = {}
    seen = set()
    for seat in seats:
        try:
            found = assembler.closure(None, EXTERNAL_SEATS, solutions=(seat,), every_arm=every_arm)
        except AssemblyError as error:
            unresolved[seat] = str(error)
            continue
        for member in found:
            if member.label not in seen:
                seen.add(member.label)
                members.append(member)
    return members, unresolved


def vendor_members(assembler=None) -> list:
    """The hub's vendor arms of ``vendor-model-caller`` (anthropic, gemini, openai, deepseek) that ``hub.make_provider`` builds."""
    found, _ = members_for((hub.CALL_A_MODEL,), assembler, every_arm=True)
    return [m for m in found if m.label.split(":", 1)[-1] in hub.VENDOR_KEY_VARIABLES]


def selected_entries(assembler=None) -> Tuple[list, Dict[str, str]]:
    """``(entries, unresolved)`` for the selected arms of every hub seat, each requirement once with who uses it."""
    members, unresolved = members_for(hub.seats(), assembler)
    return esoi_requirements.gather(esoi_requirements.members_pairs(members)), unresolved


QAR_FILLED_ENV = {"delegated-agent-sessions": ("HUBOFHUBS_WRITE_ROOT",)}   # QAR builds that arm itself with its own working directory, so the hub's variable is never read


def unused_seats(environ: Mapping[str, str]) -> set:
    """Seats QAR does not use in this process: ``intake-sources`` (the OpenClaw arm) only runs under ``channel`` and needs
    ``QAR_CHANNEL_PROVIDER``; a lane or chat without it never builds that arm, so its requirements must not fail a check."""
    return set() if (environ.get("QAR_CHANNEL_PROVIDER") or "").strip() else {"intake-sources"}


def in_use(entry, environ: Mapping[str, str]) -> bool:
    """False when every user of the requirement is a seat QAR does not use here, or a variable QAR fills itself."""
    skipped = unused_seats(environ)
    names = tuple(getattr(entry.requirement, "names", ()) or ())
    users = [u.split(":")[0] for u in entry.used_by]
    if users and all(u in skipped for u in users):
        return False
    if users and all(any(n in QAR_FILLED_ENV.get(u, ()) for n in names) for u in users):
        return False
    return True


def requirements_report(environ: Optional[Mapping[str, str]] = None, assembler=None) -> Report:
    """The unmet requirements of what QAR's assembly would use, checked offline against ``environ`` (default: the process
    environment plus what the lane's config supplies: its ``env`` table and fields such as ``corpus_root``, which stands for ``QAR_CORPUS_ROOT``; the
    process environment wins, as it does at run time). Safe to call at any time: no model call, no network, no value printed."""
    if environ is None:
        from quest_ai_runner.the_body.configuration.config_environment import lane_supplied_environment
        environ = {**lane_supplied_environment(), **os.environ}
    entries, unresolved = selected_entries(assembler)
    entries = [entry for entry in entries if in_use(entry, environ)]
    skipped = unused_seats(environ)
    unresolved = {seat: why for seat, why in unresolved.items() if seat not in skipped}
    checks = esoi_requirements.check(entries, environ, offline=True)
    items = [Item(label=esoi_requirements.describe(entry.requirement), kind=entry.requirement.kind, status=one.status,
                  required=bool(entry.requirement.required), blocking=one.blocking, remedy=one.remedy, used_by=tuple(entry.used_by))
             for entry, one in zip(entries, checks)]
    return Report(items, unresolved)


def startup_notice(environ: Optional[Mapping[str, str]] = None, assembler=None) -> Optional[str]:
    """One line for the terminal's header when something REQUIRED is unmet, else None (a calm start says nothing).
    Never raises: a failure to compute the report is not a reason to disturb a start."""
    try:
        report = requirements_report(environ, assembler)
    except Exception:  # noqa: BLE001
        return None
    unmet = report.unmet()
    if not unmet:
        return None
    return f"{len(unmet)} required setup item(s) unmet; run `{DOCTOR_COMMAND}` for the fix."


def env_entries(assembler=None) -> list:
    """The hub's requirements for the template: what QAR uses plus the vendor arms it can build."""
    members, _ = members_for(hub.seats(), assembler)
    present = {m.label for m in members}
    members += [m for m in vendor_members(assembler) if m.label not in present]
    return esoi_requirements.gather(esoi_requirements.members_pairs(members))


def hub_env_template(assembler=None) -> str:
    """The text ``esoi requirements --env-template`` writes for QAR's assembly: every hub-declared variable, blank."""
    return esoi_requirements.env_template(env_entries(assembler))


def hub_env_names(assembler=None) -> List[str]:
    """Every environment variable the hub's declarations name for QAR's assembly (primary and alternative names)."""
    names: List[str] = []
    for entry in env_entries(assembler):
        item = entry.requirement
        key = getattr(item, "key", None)
        for env in (item, key):
            if env is not None and hasattr(env, "names"):
                names.extend(n for n in env.names if n not in names)
    return names


def hub_env_descriptions(assembler=None) -> Dict[str, str]:
    """{variable: one-line description} from the hub's declarations, so ``esoi/env_descriptions.csv`` need not repeat them."""
    out: Dict[str, str] = {}
    for entry in env_entries(assembler):
        item = entry.requirement
        if getattr(item, "key", None) is not None:
            for name in item.key.names:
                out.setdefault(name, f"{item.service} API key; declared by the hub for {', '.join(sorted({u.split(':')[0] for u in entry.used_by}))}.")
        elif hasattr(item, "names") and getattr(item, "option", None):
            for name in item.names:
                out.setdefault(name, f"Fills the {item.option!r} option of {', '.join(entry.used_by)}; declared by the hub.")
    return out


def render_block(assembler=None) -> str:
    """The generated block of ``.env.example``, markers included."""
    return BEGIN_MARK + "\n" + hub_env_template(assembler).rstrip("\n") + "\n" + END_MARK + "\n"


def block_of(text: str) -> Optional[str]:
    """The generated block found in a file's text, markers included, or None."""
    start = text.find(BEGIN_MARK)
    end = text.find(END_MARK)
    if start < 0 or end < start:
        return None
    return text[start:end + len(END_MARK)] + "\n"


def sync_env_example(path: str, write: bool = True, assembler=None) -> bool:
    """Make the generated block of ``path`` equal the hub's declarations. Returns True when it already did. With ``write`` False
    only compares. A file with no block gets one appended."""
    text = open(path, encoding="utf-8").read()
    wanted = render_block(assembler)
    current = block_of(text)
    if current == wanted:
        return True
    if write:
        updated = text.replace(current, wanted) if current else text.rstrip("\n") + "\n\n" + wanted
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(updated)
    return False


def main(argv: Optional[Sequence[str]] = None) -> int:
    args = list(sys.argv[1:] if argv is None else argv)
    if len(args) == 2 and args[0] in ("--write-env-example", "--check-env-example"):
        same = sync_env_example(args[1], write=args[0] == "--write-env-example")
        if args[0] == "--check-env-example":
            print("generated block matches the hub's declarations" if same else "generated block differs from the hub's declarations")
            return 0 if same else 1
        print("already current" if same else "updated")
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
