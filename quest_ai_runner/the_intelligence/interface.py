"""The interface of Quest Intelligence (the lines that turn one request into a response). Importing this module runs nothing."""
from __future__ import annotations

import typing
from typing import Any, Mapping, Optional, Sequence

from esoi import solution


@solution("quest-intelligence", kind="event", entry="view", example={"request": "what is the latest Rust version?"})
@typing.runtime_checkable
class IntelligenceFlowing(typing.Protocol):
    """One request's handling, each line handed to the member that owns it: ``hold`` the intent a quest holds, ``view`` the request against the
    person's intents, ``prepare`` the context it needs, ``think`` it through, ``watch`` a run for risk, ``measure`` the work against its metric,
    ``gate`` whether standing work may start and ``due`` the standing work that is due."""

    def hold(self, quest_id: str, message: str = "") -> Mapping[str, Any]: ...
    def view(self, request: str, person: str = "", objectives: Sequence[Mapping[str, Any]] = (), stated: Optional[Mapping[str, Any]] = None,
             now: str = "") -> Mapping[str, Any]: ...
    def prepare(self, request: str) -> Mapping[str, Any]: ...
    def think(self, request: str, **inputs: Any) -> Mapping[str, Any]: ...
    def watch(self, digest: str) -> Any: ...
    def measure(self, case: Mapping[str, Any]) -> Mapping[str, Any]: ...
    def gate(self, quest_id: str, now: str = "") -> Mapping[str, Any]: ...
    def due(self, schedules: Sequence[Mapping[str, Any]], now: str = "", priorities: Optional[Mapping[str, Any]] = None) -> Sequence[Mapping[str, Any]]: ...
